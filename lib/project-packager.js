/**
 * Project Packager
 * Generates a complete, ready-to-run Vite + React 19 + Tailwind CSS project in a single ZIP file.
 */

const AdmZip = require('adm-zip');
const { exportTailwindConfig } = require('./design-tokens-exporter');

function createProjectZip(code = '', telemetry = {}, options = {}) {
  const zip = new AdmZip();
  const title = (telemetry.meta?.title || 'site-clone').toLowerCase().replace(/[^a-z0-9_-]/g, '-');
  const tailwindCfg = exportTailwindConfig(telemetry);

  // 1. package.json
  const packageJson = {
    name: title,
    private: true,
    version: '0.0.0',
    type: 'module',
    scripts: {
      dev: 'vite',
      build: 'tsc -b && vite build',
      preview: 'vite preview',
    },
    dependencies: {
      react: '^19.0.0',
      'react-dom': '^19.0.0',
      'lucide-react': '^0.475.0',
    },
    devDependencies: {
      '@types/react': '^19.0.0',
      '@types/react-dom': '^19.0.0',
      '@vitejs/plugin-react': '^4.3.4',
      autoprefixer: '^10.4.20',
      postcss: '^8.5.2',
      tailwindcss: '^3.4.17',
      typescript: '~5.7.2',
      vite: '^6.1.0',
    },
  };

  zip.addFile('package.json', Buffer.from(JSON.stringify(packageJson, null, 2), 'utf8'));

  // 2. vite.config.ts
  const viteConfig = `import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
});
`;
  zip.addFile('vite.config.ts', Buffer.from(viteConfig, 'utf8'));

  // 3. tsconfig.json
  const tsConfig = {
    compilerOptions: {
      target: 'ES2020',
      useDefineForClassFields: true,
      lib: ['ES2020', 'DOM', 'DOM.Iterable'],
      module: 'ESNext',
      skipLibCheck: true,
      moduleResolution: 'bundler',
      allowImportingTsExtensions: true,
      isolatedModules: true,
      moduleDetection: 'force',
      noEmit: true,
      jsx: 'react-jsx',
      strict: true,
      noUnusedLocals: true,
      noUnusedParameters: true,
      noFallthroughCasesInSwitch: true,
    },
    include: ['src'],
  };
  zip.addFile('tsconfig.json', Buffer.from(JSON.stringify(tsConfig, null, 2), 'utf8'));

  // 4. tailwind.config.js & postcss.config.js
  zip.addFile('tailwind.config.js', Buffer.from(tailwindCfg, 'utf8'));
  const postcssConfig = `module.exports = {
  plugins: {
    tailwindcss: {},
    autoprefixer: {},
  },
};
`;
  zip.addFile('postcss.config.js', Buffer.from(postcssConfig, 'utf8'));

  // 5. index.html
  const indexHtml = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <link rel="icon" type="image/svg+xml" href="/vite.svg" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${telemetry.meta?.title || 'Site Clone'}</title>
  </head>
  <body class="bg-[#0B0B0C] text-[#FFFFFF]">
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`;
  zip.addFile('index.html', Buffer.from(indexHtml, 'utf8'));

  // 6. src/index.css
  const indexCss = `@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
  color-scheme: dark;
}
`;
  zip.addFile('src/index.css', Buffer.from(indexCss, 'utf8'));

  // 7. src/main.tsx
  const mainTsx = `import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App';
import './index.css';

ReactDOM.createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);
`;
  zip.addFile('src/main.tsx', Buffer.from(mainTsx, 'utf8'));

  // 8. src/App.tsx (Use generated code or default starter)
  const appTsx = code || `import React from 'react';

export default function App() {
  return (
    <div className="min-h-screen flex items-center justify-center p-8 bg-slate-900 text-white">
      <div className="max-w-md text-center space-y-4">
        <h1 className="text-2xl font-bold">SitePrompter Generated Project</h1>
        <p className="text-slate-400">Clone is ready. Paste your generated App.tsx component here.</p>
      </div>
    </div>
  );
}
`;
  zip.addFile('src/App.tsx', Buffer.from(appTsx, 'utf8'));

  // 9. README.md
  const readmeMd = `# ${telemetry.meta?.title || 'Site Clone Project'}

Generated by **SitePrompter Web — Pro SaaS Edition**.

## 🚀 Quick Start

1. Install dependencies:
   \`\`\`bash
   npm install
   \`\`\`

2. Run local development server:
   \`\`\`bash
   npm run dev
   \`\`\`

3. Open your browser at \`http://localhost:5173\`.

## 🛠️ Tech Stack
- **Framework**: React 19 + TypeScript + Vite
- **Styling**: Tailwind CSS
- **Icons**: Lucide React
`;
  zip.addFile('README.md', Buffer.from(readmeMd, 'utf8'));

  return zip.toBuffer();
}

module.exports = {
  createProjectZip,
};
